#!/usr/bin/env python3
"""Build a branch-native evaluation fixture from this repository's real .sdd/ corpus.

The v2 methodology hand-built synthetic .sdd/ trees (see build_fixtures*.py). That was
necessary while the two generations' layouts had to be simulated, but this repository
dogfoods its own plugin: `main` and `develop` each carry a *real*, internally consistent
.sdd/ tree matched to that branch's skills. Checking out the branch therefore produces a
era-consistent fixture for free, with none of the hand-authoring that leaked v5 conventions
into the v4 sandbox (ASSERTION_DESIGN.md, defect 2).

One correction is still required. `.sdd/AI-SDD-PRINCIPLES.md` and
`.claude/rules/ai-sdd-instructions.md` are generated by the SessionStart hook from the
*installed* plugin, not from the branch under test (see .claude/rules/plugin-development.md),
so both branches currently commit v4.1.0 content. Handing that to `develop`'s skills would
evaluate them against a rulebook they do not implement. This script re-renders both files
from the branch's own plugin source, i.e. it simulates "this branch has been released and
installed" -- which is the state the branch's skills are written for.

`--skill-from <ref>` builds a **synthetic control** cell: the corpus stays era-native, but the
skill under test is replaced by another ref's copy. Give both eras the same ref and the two
lifts differ only by noise, by construction. That is stronger than relying on a skill that
happens not to have changed -- iteration-1 used `analyze-requirements` as a zero-diff control
and lost it the moment the defect the measurement itself found got fixed on develop
(issue #111 / PR #114). A control the measurement can invalidate is not a control.

Usage:
    build_sdd_fixture.py <branch> <outdir> [--eval <path/to/evals.json>] [--eval-id N]
                         [--skill-from <ref>]

Exit codes: 0 = built, 1 = error.
"""

import argparse
import json
import re
import shutil
import subprocess
import sys
from pathlib import Path
from typing import Dict, List, Optional, Tuple

# The eval definitions state, in plain text, exactly what each run is graded on. Leaving
# them inside the sandbox would let a run read its own answer key, so they never ship.
EXCLUDE_PREFIXES = (".claude/skill-evals",)

# Generated by sdd_index.py at session start; a stale copy would answer questions the run
# is supposed to work out from the documents themselves.
GENERATED_PATHS = (".sdd/.cache",)

FRONT_MATTER_RE = re.compile(r"\A---\r?\n.*?\r?\n---\r?\n", re.DOTALL)


def run_git(args: List[str], cwd: Path) -> str:
    result = subprocess.run(
        ["git"] + args, cwd=str(cwd), capture_output=True, text=True, check=False
    )
    if result.returncode != 0:
        raise RuntimeError(f"git {' '.join(args)} failed: {result.stderr.strip()}")
    return result.stdout


def repo_root() -> Path:
    return Path(run_git(["rev-parse", "--show-toplevel"], Path.cwd()).strip())


def export_tree(branch: str, out_dir: Path, root: Path) -> str:
    """Extract the branch's whole tree into out_dir and return its commit sha."""
    sha = run_git(["rev-parse", branch], root).strip()
    out_dir.mkdir(parents=True, exist_ok=True)
    archive = subprocess.run(
        ["git", "archive", "--format=tar", sha],
        cwd=str(root),
        capture_output=True,
        check=False,
    )
    if archive.returncode != 0:
        raise RuntimeError(f"git archive {branch} failed: {archive.stderr.decode(errors='replace')}")

    extract = ["tar", "-x", "-C", str(out_dir)]
    for prefix in EXCLUDE_PREFIXES:
        extract += ["--exclude", f"{prefix}*"]
    result = subprocess.run(extract, input=archive.stdout, capture_output=True, check=False)
    if result.returncode != 0:
        raise RuntimeError(f"tar extract failed: {result.stderr.decode(errors='replace')}")
    return sha


def read_plugin_version(out_dir: Path) -> str:
    manifest = out_dir / "plugins" / "sdd-workflow" / ".claude-plugin" / "plugin.json"
    try:
        return json.loads(manifest.read_text(encoding="utf-8")).get("version", "")
    except (OSError, json.JSONDecodeError):
        return ""


def read_sdd_root(out_dir: Path) -> str:
    config = out_dir / ".sdd-config.json"
    try:
        return json.loads(config.read_text(encoding="utf-8")).get("root", ".sdd")
    except (OSError, json.JSONDecodeError):
        return ".sdd"


def render_rulebook(out_dir: Path, sdd_root: str, version: str) -> List[str]:
    """Re-render the two hook-generated files from the branch's own plugin source.

    Mirrors sync_principles_file / sync_rules_files in
    plugins/sdd-workflow/scripts/session-start.py. Kept as a deliberate duplication rather
    than an import: the fixture must reflect the *branch's* source, and importing the
    working tree's copy of the hook would silently mix generations.
    """
    plugin_root = out_dir / "plugins" / "sdd-workflow"
    applied: List[str] = []

    source = plugin_root / "AI-SDD-PRINCIPLES.source.md"
    target = out_dir / sdd_root / "AI-SDD-PRINCIPLES.md"
    if source.is_file():
        content = source.read_text(encoding="utf-8")
        if version:
            content = re.sub(r"^version:.*$", f'version: "{version}"', content, flags=re.MULTILINE)
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(content, encoding="utf-8")
        applied.append(f"rendered {sdd_root}/AI-SDD-PRINCIPLES.md from the branch's source")

    template = plugin_root / "skills" / "sdd-init" / "templates" / "ai_sdd_instructions_rules.md"
    rules_target = out_dir / ".claude" / "rules" / "ai-sdd-instructions.md"
    if template.is_file():
        content = template.read_text(encoding="utf-8")
        content = content.replace("{SDD_ROOT}", sdd_root)
        if version:
            content = content.replace("{PLUGIN_VERSION}", version)
        rules_target.parent.mkdir(parents=True, exist_ok=True)
        rules_target.write_text(content, encoding="utf-8")
        applied.append(".claude/rules/ai-sdd-instructions.md rendered from the branch's template")

    return applied


def override_skill(out_dir: Path, skill: str, ref: str, root: Path) -> List[str]:
    """Replace one skill's directory with another ref's copy (synthetic control)."""
    rel = f"plugins/sdd-workflow/skills/{skill}"
    target = out_dir / rel
    if not target.is_dir():
        return [f"MISSING skill directory, not overridden: {rel}"]
    shutil.rmtree(target)
    target.mkdir(parents=True)
    archive = subprocess.run(
        ["git", "archive", "--format=tar", f"{ref}:{rel}"],
        cwd=str(root),
        capture_output=True,
        check=False,
    )
    if archive.returncode != 0:
        raise RuntimeError(
            f"git archive {ref}:{rel} failed: {archive.stderr.decode(errors='replace')}"
        )
    result = subprocess.run(
        ["tar", "-x", "-C", str(target)], input=archive.stdout, capture_output=True, check=False
    )
    if result.returncode != 0:
        raise RuntimeError(f"tar extract failed: {result.stderr.decode(errors='replace')}")
    sha = run_git(["rev-parse", ref], root).strip()[:12]
    return [f"synthetic control: {rel} replaced with {ref} @ {sha}"]


def drop_generated(out_dir: Path) -> List[str]:
    applied: List[str] = []
    for rel in GENERATED_PATHS:
        path = out_dir / rel
        if path.is_dir():
            shutil.rmtree(path)
            applied.append(f"removed generated {rel}/")
        elif path.is_file():
            path.unlink()
            applied.append(f"removed generated {rel}")
    return applied


def strip_front_matter(path: Path) -> bool:
    text = path.read_text(encoding="utf-8")
    stripped = FRONT_MATTER_RE.sub("", text, count=1)
    if stripped == text:
        return False
    path.write_text(stripped, encoding="utf-8")
    return True


def load_eval_fixture(eval_path: Path, eval_id: Optional[int]) -> Tuple[str, Dict]:
    data = json.loads(eval_path.read_text(encoding="utf-8"))
    evals = data.get("evals", [])
    if not evals:
        raise RuntimeError(f"{eval_path} declares no evals")
    if eval_id is None:
        chosen = evals[0]
    else:
        matches = [e for e in evals if e.get("id") == eval_id]
        if not matches:
            raise RuntimeError(f"{eval_path} has no eval with id {eval_id}")
        chosen = matches[0]
    return data.get("skill_name", eval_path.parent.name), chosen


def apply_eval_fixture(out_dir: Path, eval_path: Path, spec: Dict) -> List[str]:
    """Apply an eval's `fixture` block. Every transform is declared in evals.json so the
    same scenario is reproduced identically for all four variants."""
    fixture = spec.get("fixture") or {}
    applied: List[str] = []

    if fixture.get("corpus") == "empty-project":
        # sdd-init is graded on introducing the workflow, so it must not start from a
        # project that already has it -- CLAUDE.md's existing AI-SDD Instructions section
        # would otherwise make the run a no-op "already up to date". Keep
        # .sdd-config.json: the skill errors without one (a real, documented behaviour),
        # and grading that error is not what this eval is for.
        for rel in (".sdd", ".claude/rules/ai-sdd-instructions.md", "CLAUDE.md"):
            path = out_dir / rel
            if path.is_dir():
                shutil.rmtree(path)
                applied.append(f"emptied {rel}/")
            elif path.is_file():
                path.unlink()
                applied.append(f"emptied {rel}")

    for rel in fixture.get("remove", []):
        path = out_dir / rel
        if path.is_dir():
            shutil.rmtree(path)
            applied.append(f"removed {rel}/")
        elif path.is_file():
            path.unlink()
            applied.append(f"removed {rel}")
        else:
            applied.append(f"MISSING (not removed): {rel}")

    for rel in fixture.get("strip_front_matter", []):
        path = out_dir / rel
        if path.is_file() and strip_front_matter(path):
            applied.append(f"stripped front matter from {rel}")
        else:
            applied.append(f"MISSING or had no front matter: {rel}")

    scenario_dir = eval_path.parent / "scenario"
    for rel in fixture.get("copy_scenario", []):
        src = scenario_dir / rel
        dst = out_dir / rel
        if not src.is_file():
            applied.append(f"MISSING scenario file: {src}")
            continue
        dst.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(src, dst)
        applied.append(f"copied scenario/{rel} -> {rel}")

    return applied


def write_manifest(
    out_dir: Path,
    branch: str,
    sha: str,
    version: str,
    skill: Optional[str],
    eval_name: Optional[str],
    applied: List[str],
) -> None:
    lines = [
        "# Fixture manifest",
        "",
        "Generated by `.claude/skill-evals/build_sdd_fixture.py`. Not part of the corpus under test.",
        "",
        f"- branch: `{branch}`",
        f"- commit: `{sha}`",
        f"- plugin version (as rendered into the rulebook): `{version or 'unknown'}`",
        f"- skill: `{skill or '-'}`",
        f"- eval: `{eval_name or '-'}`",
        "",
        "## Transforms applied",
        "",
    ]
    lines += [f"- {item}" for item in applied] or ["- (none)"]
    lines.append("")
    lines.append(
        "The `skill` and `without` variants share this fixture byte for byte; the only "
        "difference between them is whether the branch's SKILL.md is loaded."
    )
    lines.append("")
    (out_dir / "FIXTURE.md").write_text("\n".join(lines), encoding="utf-8")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("branch", help="branch or commit to build the fixture from (e.g. main, develop)")
    parser.add_argument("outdir", help="destination directory (must not already exist)")
    parser.add_argument("--eval", dest="eval_path", help="path to a skill's evals.json, to apply its fixture block")
    parser.add_argument("--eval-id", type=int, default=None, help="which eval id to use (default: the first)")
    parser.add_argument(
        "--skill-from",
        dest="skill_from",
        help="replace the skill under test with this ref's copy, for a synthetic control cell",
    )
    args = parser.parse_args()

    out_dir = Path(args.outdir).resolve()
    if out_dir.exists() and any(out_dir.iterdir()):
        print(f"ERROR: {out_dir} already exists and is not empty", file=sys.stderr)
        return 1

    try:
        root = repo_root()
        sha = export_tree(args.branch, out_dir, root)
        version = read_plugin_version(out_dir)
        sdd_root = read_sdd_root(out_dir)

        applied = drop_generated(out_dir)
        applied += render_rulebook(out_dir, sdd_root, version)

        skill: Optional[str] = None
        eval_name: Optional[str] = None
        if args.eval_path:
            eval_path = Path(args.eval_path).resolve()
            skill, spec = load_eval_fixture(eval_path, args.eval_id)
            eval_name = spec.get("eval_name")
            applied += apply_eval_fixture(out_dir, eval_path, spec)
            if args.skill_from:
                applied += override_skill(out_dir, skill, args.skill_from, root)
        elif args.skill_from:
            raise RuntimeError("--skill-from requires --eval to know which skill to replace")

        write_manifest(out_dir, args.branch, sha, version, skill, eval_name, applied)
    except (RuntimeError, OSError, json.JSONDecodeError) as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 1

    print(f"[build_sdd_fixture] {args.branch} @ {sha[:12]} -> {out_dir}")
    for item in applied:
        print(f"  - {item}")
    if any(item.startswith("MISSING") for item in applied):
        print(
            "[build_sdd_fixture] NOTE: some declared transforms found no target. Expected when the "
            "eval declares `main_counterpart: none` (a develop-only capability has nothing to "
            "transform in main's corpus); otherwise the scenario is not what evals.json describes "
            "and should be fixed before measuring.",
            file=sys.stderr,
        )
    return 0


if __name__ == "__main__":
    sys.exit(main())
